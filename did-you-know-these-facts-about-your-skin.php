               <h3 class="f-medium">Here are some facts you probably don’t know about your skin:</h3>
               <ul  class="dots-list">
                  <li class="f-regular">The skin is the largest organ in the human body. Yes, it is an organ; made to protect the bones, muscles and internal organs from bacteria, water loss, and other environmental hazards such as pathogens. Its area stretches out to around 2 square meters and it accounts for 16 per cent of your body weight.</li>
                 
                  <li class="f-regular">Your skin sheds dead cells every day; so much so that your skin regenerates in its entirety within 28 days. Even while you sleep your skin undergoes its natural exfoliation process and keeps removing dead skin cells. These cells can stay on your skin, so you have to use a gentle exfoliator such as an ayurvedic anti marks exfoliating face scrub to remove them.</li>
                  <li class="f-regular">Your skin helps regulate body temperature. Your body uses its internal ‘thermostat’ to adjust itself to different seasons and weather patterns. In cold weather, the blood vessels contract and blood flow reduction to maintain the heat within the body and keep you warm. When it’s hot, your skin starts sweating to increase the blood flow in your capillaries, which makes you sweat more and the evaporation of that sweat on your skin cools your body down.</li>
                 <li class="f-regular">Tattoos stay permanent, despite the natural regeneration of the skin because of white blood cells (WBCs). The puncture of the needle causes inflammation in the dermis, which is the middle layer of your skin. WBCs are sent in to repair the damage. They eat the dye and pass it on to other macrophages when they die. So essentially, the tattoo pigment transfers to newer cells.</li>
                  <li class="f-regular">People can have different types of skin – mostly oily, normal, and dry. These types of skin react differently and age differently as well. Maintain your hygiene by washing your face with a mild face wash such as Nomarks Ayurvedic Antimarks face wash and keep your skin feeling fresh. If your skin is sensitive to generic products, look for something that would not only suit it but work wonders on it in the long run. The ingredients used in products like creams should be customized for different types of skin. Bajaj Nomarks Ayurvedic Antimarks Cream comes in three variants for dry, normal and oily skin. It has ingredients such as neem, turmeric, aloe vera, calendula, almond oil and many more which are bringing about positive results on different kinds of skin types. These ingredients work together from day 1 to help remove pimple marks, dark spots, and blemishes, leaving your skin clear.</li>
                  <li class="f-regular">The thickness and flexibility of your skin vary in different parts of the body. The thinnest skin is only 0.02 mm and it is present in the area near the eye, especially the eyelid. The thickest is 1.4 mm and is present on the soles of your feet. Similarly, the most flexible skin is on your knuckles whereas the skin on your arm isn’t as flexible.</li>
                  <li class="f-regular">The skin is a very versatile organ that has to bear the brunt because it’s constantly exposed. Different elements – excessive sun, dust, hectic lifestyle and pollution – can affect your skin and make it suffer.</li>
                  <li class="f-regular">These show up on your skin as acne, pigmentation or blemishes. Keeping your skin healthy requires a lot of tender love, and care. Combat these signs and save your skin from damage while also keeping it healthy in your fast-paced lifestyle by using Bajaj Nomarks Ayurvedic Antimarks cream which is available for oily, normal, and dry skin. It works from day one to reduce pimples, dark spots and blemishes, along with their face wash, and soap.</li>


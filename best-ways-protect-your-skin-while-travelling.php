               </div>
               <p class="f-regular">Travelling can take a toll on your skin as it can dehydrate the skin due to a lack of oxygen, harsh winds and extreme temperature changes can cause pimples too. Add to that the exhaustion, a change in diet, and a hectic schedule, and you have a recipe for skin disaster.</p> 
                 <p class="f-regular">But did you know you can take some preventive measures (and products) to ensure this doesn’t happen? Read on to know more.</p> 
                  <ul data-aos="fade-up" data-aos-duration="1000" data-aos-delay="150">
                  <li class="f-semibold">1. Moisturize your skin</li>
                  <p class="f-regular">Make sure you carry a moisturizer with you when you travel and apply it regularly. The night before you go, apply intense moisturizer to keep your skin hydrated and as a preventive measure against direct sunlight and strong winds. Besides, it can counteract the extreme dryness in the flight.</p>
                  

                  <li class="f-semibold">2. Drink plenty of water</li>
                  <p class="f-regular">With weather fluctuations and being exposed to the elements, your skin can easily lose its moisture. Hence, it is essential to hydrate your skin by drinking plenty of water regularly. Make sure you carry a bottle of water at all times while travelling and make it a point to sip from it frequently. Avoid aerated and sugar-laden beverages with your meals and stick to water instead. If you’re drinking alcohol, make sure you have one glass of water for every glass of alcohol consumed.</p>

                  <li class="f-semibold">3. Cover your face with a scarf</li>
                  
                  <p class="f-regular">Dust, pollution, and temperature changes can ruin your skin, leading it to break out and dry out like a prune. To keep the damage to your skin minimal, ensure that you carry a scarf at all times and keep your face covered with it, especially when walking or riding a scooter or convertible. It may not seem like a lot, but your skin will thank you for it.</p>
                  
                  <li class="f-semibold">4. Use Sunscreens</li>
                  <p class="f-regular">While travelling your skin has to go through different conditions such as dryness, acclimatization to new air and even new amount of heat exposure. Therefore, always carry a sunscreen to keep your skin protected from the harsh sun.</p>
                 
                  <li class="f-semibold">5. Pack a cleanser</li>
                  <p class="f-regular">While travelling, it’s normal for your skin to attract a lot of dirt and dust, which when accumulated can lead to breakouts. A cleanser is the best tool in your arsenal to clear out all that grime. Not only will it clean all the dirt, it will also keep your skin refreshed, clean, and hydrated.</p>
                   <li class="f-semibold">6. Keep a cloth or wet wipes</li>
                  <p class="f-regular">While travelling, any dust and dirt on your skin can be wiped off instantly with wet wipes. Make sure you dab your skin every couple of hours with a wet wipe to get rid of the debris. Remember to reapply sunscreen and moisturizer each time though.</p>
                   <li class="f-semibold">7. Get your beauty sleep</li>
                  <p class="f-regular">Hectic schedules involving late nights and early mornings mean you don’t get adequate rest. While it makes you feel lethargic and tired, it’s your skin that suffers the most. Not getting enough sleep means your skin isn’t getting enough rest, which in turn can cause it to rebel and break out. To avoid all this, it is important to get 7-8 hours of sleep each night.</p>

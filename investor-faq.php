                  <div id="innercollapseTwo" class="collapse" aria-labelledby="innerheadingTwo" data-parent="#inner-accordion">
                     <div class="card-body">
                       <p class="f-book">SEBI has notified various companies whose shares shall be traded in demat form only. By virtue of such notification, the shares of the Company are also subject to compulsory trading in demat form on the Stock Exchanges. According to the Depositories Act, 1996, an investor has the option to hold securities either in physical or electronic form. Part of holding can be in physical form and part in demat form. However, SEBI has notified that settlement of market trades in listed securities should take place only in the demat mode.</p>
                       <h5 class="f-medium">Following are the benefits of Dematerialization of shares:</h5>
                       <ul class="f-book">
                          <li>Convenient mode of holding shares, especially if you are holding shares of many companies;</li>
                          <li>Immediate transfer of securities;</li>
                          <li>No stamp duty is payable on transfer of shares;</li>
                          <li>Elimination of risks associated with physical certificates such as bad delivery, fake securities, delays, thefts etc;</li>
                          <li>Reduction in paper work involved in transfer of securities;</li>
                          <li>Reduction in transaction cost;</li>
                          <li>No odd lot problem, even one share can be traded;</li>
                          <li>Nomination facility;</li>
                          <li>Saving of time – Change in address / bank account particulars etc. recorded with DP gets registered electronically with all companies in which the investor holds securities. Thus eliminating the need to correspond with each of the companies separately. Further, transmission of securities (in the event of death of the shareholder) is done by the DP, eliminating the need to correspond with all companies and following different procedures laid by them;</li>
                          <li>Facilitates direct credit of shares in case of allotment under IPO, Rights, Bonus, Split etc. and direct credit of dividend to shareholders designated account.</li>
                          <li>Holding investments in equity and debt instruments in a single account.</li>
                       </ul>

                     <div class="card-body">
                         <ul class="f-book">
                            <li>Open a Beneficiary Account with a DP registered with SEBI and with any one of the Depositories i.e., NSDL or CDSL.</li>
                            <li>Submit the Dematerialization Request Form (DRF) as given by DP duly filled in and signed by all the shareholders, along with share certificate(s) and requisite documents. Ensure that the names and order of names as per certificate(s) matches with the names and order of the names as per the DP account.</li>
                            <li>Obtain an acknowledgement from the DP on handing over the share certificate(s).</li>
                            <li>On receipt of DRF as above, DP will generate a Dematerialization Request Number (DRN) and the said DRN is electronically transmitted to the Company / Registrar and Transfer Agent (RTA) through the concerned Depository.</li>
                            <li>Simultaneously, DP will send the physical certificate(s) with the original DRF to the Company/RTA for verification and confirmation.</li>
                            <li>The Company/RTA, on receipt of DRF and share certificate(s) as above, will process the said request and if the DRF is found to be in order {viz. verification of signature and certificate(s)}, will electronically confirm the said request.</li>
                            <li>The DP on receipt of such confirmation, will update the demat account of the investor.</li>
                            <li>As per regulations in force presently, the dematerialization process should be completed within 21 days from the date of receipt of demat request at RTA.</li>
                         </ul>

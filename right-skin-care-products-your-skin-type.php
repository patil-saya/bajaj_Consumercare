                  <p class="f-regular">Skin types and its susceptibilities are genetically determined, but various internal and external factors could alter the characteristics of your natural skin type. Broadly, skin types can be classified into five categories- normal, dry, oily, combination, and sensitive.</p>

               </div>
               <p class="f-regular">Listed below are the characteristics of different skin types and how you can determine the right products for each.</p> 
                  <ul data-aos="fade-up" data-aos-duration="1000" data-aos-delay="150">
                  <li class="f-semibold">1. Normal Skin</li>
                  <p class="f-regular">Scientifically termed ‘eudermic’, normal skin is neither too dry nor too oily. It is well-balanced and has small pores and even texture. This type of skin generally requires minimal care. But to prolong its natural state, it is best to use products that can help maintain it.</p>
                  <p class="f-regular">Using an anti marks cream and cleanser like Bajaj Nomarks Antimarks Cream For Normal Skin and Bajaj Nomarks Exfoliating Scrub can induce a natural glow in your skin.</p>

                  <li class="f-semibold">2. Dry Skin</li>
                  <p class="f-regular">Dry skin is characterized by a lack of natural oils in the skin. It generally tends to feel taut and flaky without any moisturization. It also tends to age faster as the lack of moisture makes it more susceptible to wrinkling and prolongs healing.</p>
                  <p class="f-regular">For this reason, it requires intensive care. Bajaj Nomarks Antimarks Facewash For Dry Skin gently cleanses and has Wheat Germ Oil that softens dry skin. Applying an ayurvedic face cream for dry skin like Bajaj Nomarks Antimarks Cream after cleansing can keep your skin blemish-free and healthy.</p>

                  <li class="f-semibold">3. Oily Skin</li>
                  
                  <p class="f-regular">This is one of the most difficult skin types to deal with. Characterized by excess production of sebum, it is prone to clogging up, which causes blackheads, acne and, even cysts in extreme cases. You must be careful as harsh products can strip the skin’s natural barrier of oils, which pushes it to produce more oil than it needs. Ayurvedic products are the best for such problem-prone skin.</p>
                  
                  <p class="f-regular">Products like Bajaj Nomarks Antimarks Facewash For Oily Skin have Neem, that has anti-bacterial properties. Alternatively, Bajaj Nomarks Antimarks Soap For Oily Skin has Clove that helps fight acne too. Also, Bajaj Nomarks Ayurvedic Antimarks Cream For Oily Skin, best ayurvedic cream for oily skin, has Aloe Vera that moisturizes and facilitates collagen building to repair acne marks.</p>
                  <li class="f-semibold">4. Combination Skin</li>
                  <p class="f-regular">Combination skin is a mix of oily and dry skin. The T-zone, comprising of the forehead, nose, and chin, tends to get oily, and the cheeks generally feel dry. It can be tricky to find the right products for combination skin. You need to find a face cream that won’t clog pores and yet deliver moisture.</p>
                  <p class="f-regular">If you wonder how to remove dark spots from the face, use Bajaj Nomarks Antimarks Cream, with Calendula extracts, that lightens the marks and gives you clearer skin. It is also mild, ayurvedic, and non-comedogenic.</p>
                  <li class="f-semibold">5. Sensitive Skin</li>
                  <p class="f-regular">Sensitive skin can be either oily, dry, or normal, but it is very reactive and develops redness, scars, and rashes easily. It has a weak barrier and is prone to external damage. People with sensitive skin need to use mild products with natural ingredients to keep their skin calm.</p>
                  <p class="f-regular">It is important to use sunscreen whenever outdoors to prevent sun damage. Bajaj Nomarks Ayurveda Antimarks Sunscreen has Mulethi that fights tanning, and Wheat Germ Oil, a natural sunblock, that protects from sun damage. It also has Cucumber which soothes sensitive skin.</p>
                  <p class="f-regular">These types generally apply to facial skin and differ from body skin. The skin on your body is drier than facial skin as it has lesser sebaceous glands. Facial skin is also thinner and more sensitive. Besides structural differences, facial skin is also exposed to external factors for longer periods. Using heavier oil-based moisturizers during winters and light moisturizers during summers can keep your skin looking healthy from top-to-toe. However, sunscreen is something that can be applied to the body and face both. Keep in mind to listen to your skin and use products that cater to your skin’s changing needs. To keep a check on your skin health, talk to NOMA, Bajaj Nomarks’ chatbot, that can assist you in finding out the level of SkinStress™.</p>
                  

                  <p class="f-regular">Ayurveda, an ancient traditional system of medicine, has become an elusive discipline. There are two key reasons why we are losing touch with this rich tradition. First and foremost, Ayurvedic books are written in Sanskrit, which most of us don’t understand. The other reason is the western influence on our lifestyle, which has led us to believe traditional belief systems and practices are not as effective as those based on modern science.</p>
                 

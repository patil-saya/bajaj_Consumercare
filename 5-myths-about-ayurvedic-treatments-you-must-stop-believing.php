               <h3 class="f-medium" data-aos="fade-up" data-aos-duration="1000" data-aos-delay="150">Let’s dispel some of the common myths associated with Ayurveda:</h3>
                  <ul data-aos="fade-up" data-aos-duration="1000" data-aos-delay="150">
                  <li class="f-semibold">Myth #1: Ayurvedic medicine takes longer to work and is not very effective</li>
                  <p class="f-regular">Fact: One reason why Ayurvedic medicines take longer to provide results is that they don’t merely alleviate symptoms; instead they work on removing the underlying cause of the disease. Another reason for the prevalence of this myth is that people tend to try Ayurvedic medicine only after trying other medication, and this can delay the effect of Ayurveda. If it is adopted from the onset of an illness or disease, the results may be seen sooner. The time needed to cure patients depends on several factors, including how soon the problem was diagnosed, its severity, as well as how readily the body reacts to the remedy.</p>
                  <li class="f-semibold">Myth #2: Ayurveda is an outdated and obsolete system</li>
                  <p class="f-regular">Fact: Many people think of Ayurveda as an ‘exotic’ system of medicine not relying on scientific facts. However, Ayurveda has existed in our country for more than 5000 years and is still practised today due to its efficacy. It is a well-recorded form of medicine, and clinical trials and researches were widely conducted in ancient times. It was refined over thousands of years, using observation and experience— the fundamental principles of science. The old books record the diagnosis of diseases, as well as detailed facts about foods, herbs, and minerals in detail. In recent decades, with the increased realization of the importance of a holistic lifestyle and healthy eating, Ayurveda has seen a resurgence and is being accepted far and wide.</p>
                  <li class="f-semibold">Myth #3: Ayurveda medicines lack clinical testing</li>
                  <p class="f-regular">Fact: The truth is that firm guidelines have been established for quality control and standard of Ayurvedic medicines in the country. The Pharmacopoeial Laboratory of Indian Medicine (PLIM) and Central Council of Researches in Ayurvedic Sciences (CCRAS) has published the ‘Protocol for Testing of ASU Medicines’. Moreover, Rule 160 has been instituted in Drugs and Cosmetics Rules 1945 for quality control and standard of ayurvedic medicines, which ensures the establishment of drug testing laboratories throughout the country. It is mandatory for manufacturers of Ayurvedic Medicines to get certified from these laboratories regarding the quality and stability of their product.[i] However, it is best to buy Ayurvedic medicines from registered Ayurvedic practitioners and renowned brands.</p>
                  <li class="f-semibold">Myth #4: Ayurvedic treatments do not need a doctor</li>
                  <p class="f-regular">Fact: If someone gets cured by ayurvedic medicine, they advise others also to try the same. But the truth is that for specific diseases, ayurvedic treatment is based on ‘Prakriti,’ i.e. the constitution of the person’s body. Thus, blindly taking ayurvedic medicine prescribed by someone else, or opting for home remedies based on an internet search, can cause more harm than good. Instead, you should visit a registered ayurvedic practitioner or opt for proper formulations available for the treatment of specific issues from the market.</p>
                  <li class="f-semibold">Myth #5 You don’t need any ayurvedic creams for skin since you can easily use home remedies</li>
                  <p class="f-regular">You should remember that even some of the best naturally derived ingredients may at times need to be processed in a lab to isolate the good compounds and remove the bad. For example, while citrus ingredients like lime may have good antioxidants, their direct use may make skin sensitive to sun damage. Also, several essential oils need to be used with caution in particular amounts. It may not always be possible to maintain exact proportions of ingredients in home remedies, and thus right ayurvedic formulations that are made after proper research can be your friends for handling skin issues.</p>

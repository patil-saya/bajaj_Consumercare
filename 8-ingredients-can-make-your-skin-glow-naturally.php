                  <p class="f-regular">Beauty comes in all shades, and the one you are born with is lovely as it is. There is no need to change it, but you can enhance your skin tone using natural ingredients, instead of trying harmful chemicals that claim to make you fair. Most of these natural ingredients can be found in your kitchen and are safe for use.</p>

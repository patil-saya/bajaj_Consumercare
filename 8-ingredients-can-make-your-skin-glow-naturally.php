               <p class="f-regular">No matter what shade your skin is, it is beautiful. But if how to remove spots from the face is the question bothering you; here is a list of natural ingredients that can give you a glowing, spotless skin.</p> 
               <ul data-aos="fade-up" data-aos-duration="1000" data-aos-delay="150">
                  <li class="f-semibold">1. Lemon</li>
                  <p class="f-regular">Lemons, like other citrus fruits, are natural bleaching agents. They’re full of Vitamin C which promotes collagen production, making skin firmer. Lemon juice exfoliates dead skin cells and reduces the production of melanin. It has anti-bacterial properties that fight acne. Pure lemon juice may be too strong for most, so mix it in yoghurt and honey to make a mask. Apply this twice or thrice a week at night to reverse tanning.</p>
                  <li class="f-semibold">2. Honey</li>
                  <p class="f-regular">Honey is a wonderful ingredient as it is a natural bleaching agent, is moisturizing and antibacterial. It helps even skin tone and prevents acne. You can put raw honey directly onto the face or mix it in masks to get clear, glowing skin.</p>
                  <li class="f-semibold">3. Papaya</li>
                  <p class="f-regular">Papaya has papain that increases cell turnover, revealing brighter skin from within. The alpha-hydroxy acids found in papaya make it one of the best home remedies for pimple marks. You can mash a few pieces into a smooth paste and apply where needed. Leave for 20 minutes before you wash it with lukewarm water.</p>
                  <li class="f-semibold">4. Yogurt</li>
                  <p class="f-regular">Yoghurt has Lactic Acid, one of the mildest AHAs, and is suitable for sensitive skin too. It gently exfoliates and works as a melanin suppressor. Regular application of yoghurt can reduce the appearance of blemishes and enhance your skin tone. Apply directly or mixed in a mask for softness and glow.</p>
                  <li class="f-semibold">5. Licorice</li>
                  <p class="f-regular">Licorice root extracts have glabridin which inhibits tyrosinase, a melanin-producing enzyme. It has liquiritin as well that breaks melanin and removes pigmentation, making your skin look clearer. It is great for acne scar removal and soothes irritated skin too.</p>
                  <li class="f-semibold">6. Turmeric</li>
                  <p class="f-regular">Turmeric has antibacterial, anti-inflammatory and antioxidant properties, making it effective for acne-prone skin. Curcumin, present in turmeric, suppresses melanin production and instantly lightens skin tone. A popular brightening ingredient, turmeric treats various skin issues besides providing essential nutrients. You can mix half a teaspoon of turmeric in any mask to get the glow.</p>
                  <li class="f-semibold">7. Potato</li>
                  <p class="f-regular">Potatoes are packed with Vitamin B6 and effectively exfoliates and lightens skin tone. If you are wondering how to remove spots from the face, make a potato paste or extract the juice and mix with honey, lemon, or rose water to make a mask. It is very useful in removing dark circles as well.</p>
                  <li class="f-semibold">8. Gram Flour</li>
                  <p class="f-regular">Gram flour is an extremely safe yet effective, nutrient-rich skin brightener. It contains beta-carotene, niacin, riboflavin, folate acid and unsaturated fatty acids that moisturize skin while removing excess oil. It can be used as a gentle everyday cleanser by rubbing a small amount with water or rose water like a scrub. It exfoliates dead skin cells to reveal soft, healthy skin, bringing out a natural glow.</p>
                  <li class="f-semibold">9. Aloe Vera</li>
                  <p class="f-regular">Aloe Vera is one of the mildest natural bleaching agents that is ideal for people with sensitive skin, for lightening the complexion. It has a compound ‘anthraquinone’ that gently exfoliates dead skin. It also contains ‘lignin’ that improves skin’s elasticity and anti-oxidants that fight pollution and sun damage. Apply aloe vera gel directly to clean skin or mix with honey to make a mask, and with brown sugar to make a brightening scrub.</p>
                  <li class="f-semibold">10. Neem</li>
                  <p class="f-regular">Neem has antibacterial and antifungal properties that would keep acne at bay, which in turn would prevent the formation of acne marks. It also has cooling properties that would reduce redness, dark spots, blemishes and purify pollutants from pores to reveal even, glowing skin. Applying a neem and sandalwood mask can tighten skin and reduce signs of ageing, making your skin glow naturally.</p>
                  <li class="f-semibold">11. Oats</li>
                  <p class="f-regular">Oats, known as a superfood, is excellent for the skin as well due to its cleansing, exfoliating, and many other benefits. It has ‘saponin’ that flushes skin-dulling toxins and antioxidants that boost skin’s health to promote a natural glow. It also contains amino acids, vitamin B1, zinc, etc. that reverses discolouration and appearance of dark spots. Use oat milk, or ground oats with honey and milk to make a brightening mask.</p>
                  <p class="f-regular">All of the above ingredients are safe and effective methods for lightening skin naturally without any side effects. The natural bleaching agents and nutrients in these ingredients make them excellent for de-tanning and removal of marks. Bajaj Nomarks Ayurvedic Antimarks Cream has many of these ingredients like aloe vera, neem, turmeric, lemon, etc. making it the best anti marks cream. Stay away from chemicals like hydroquinone and always stick to natural products to keep your skin healthy and glowing.</p>

                        <p><b>Mumbai, India – 15/02/25 –</b> Bajaj Consumer Care Limited, a leader in India’s consumer care space, has announced the acquisition of company Vishal Personal Care that owned Banjara’s, a well-established and trusted hair and skin care brand. This announcement came on Feb 14, 2025, after the board meeting of Bajaj Consumer Care, that owns the flagship Bajaj Almond Drops brand. This strategic move aligns with Bajaj Consumer Care’s (BCCL) vision to expand its footprint across Indian markets, leveraging the growing demand for natural and Ayurvedic personal care products.</p>
                        <p>Under the terms of the agreement, Bajaj Consumer Care will acquire a 100% stake in the company in a two-phase transaction, starting with an initial 49% stake, followed by the remaining 51% in the second tranche. The estimated transaction value stands at INR 120 crore, with an enterprise value of approximately INR 108.3 crore.</p>
                        

            <div class="text-box">
            <p>Banjara’s, founded in 1991 under Vishal Personal Care Pvt Ltd in Hyderabad, has built a strong reputation for its high-quality, natural, and effective hair and skin care solutions. With a well-diversified product portfolio including facial kits, herbal powders, aloe vera gels, shampoos, and hair care powders, the brand caters to a growing segment of consumers seeking safe and natural beauty solutions which largely aligns with the values of Bajaj Consumer Care. Vishal Personal Care Pvt Ltd products boast an extensive retail presence, reaching over 70,000 outlets across thefive South Indian markets through cosmetics stores, supermarkets, pharmacies, and grocery chains.</p>
            <h4 class="yellownew mb-3">Strategic Rationale and Synergies</h4>
            <p><b>•	Enhanced Market Reach:</b><p>
            <ul class="ml-4 character-bullets">
               <li>With the acquisition of Vishal Personal Care Pvt Ltd, Bajaj Consumer Care(BCCL) will be leveraging Vishal’s extensive distribution network to deepen their penetration in South India.</li>
               <li>BCCL will also introduce brandBanjara’s products in its stronghold Hindi-speaking markets (HSM),effectively doubling its reach in both the regions.</li>
            </ul>
            <p><b>•	Brand Alignment: </b>Both Vishal Personal Care and Bajaj Consumer Care share a strong heritage rooted in Indian tradition, reinforcing consumer trust and credibility.</p>
            <p><b>•	Financial Strength: </b>Vishal Personal Care along with its brand Banjara’s has demonstrated a robust financial track record with a four-year CAGR of 14% and an annual revenue exceeding INR 50 crore. The company maintains high single-digit EBITDA margins and operates debt-free with positive cash flow.</p>
            <p><b>•	Growth in Organized Trade & International Markets:</b> Bajaj Consumer Care with the wide range of products, will scale up its presence in modern trade and export markets, capitalizing on the global trend toward natural personal care solutions.</p>
              <p>Speaking on the acquisition, Mr. Jaideep Nandi, Managing Director of Bajaj Consumer Care, said, <i>“Acquisition of Vishal Personal Care Pvt Ltd is a strategic step in strengthening Bajaj Consumer Care's footprint in the five southern markets. The addition of Banjara’s to our portfolio enhances our ability to serve the evolving consumers across India, while also complementing our product range for further expansion."</i></p>
              <p>This acquisition underscores Bajaj Consumer Care’s commitment to innovation, quality, and expansion, reinforcing its leadership in the fast-growing personal care market.</p>

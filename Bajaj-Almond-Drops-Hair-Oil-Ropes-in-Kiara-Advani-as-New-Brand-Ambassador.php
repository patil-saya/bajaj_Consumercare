                        <p>Kiara’s passion for healthy, beautiful hair fits perfectly with the Brand’s commitment for providing consumers with the nourishing strength of 6X Vitamin E and almond oil. As the new face of the Brand, she will feature in a series of high-energy marketing campaigns and events in the coming months.</p>
               

                  <p class="f-regular">According to a study published in Annals of Internal Medicine in 2013, about 90% of skin ageing is caused by the sun. This makes sunscreen one of the most important skincare products. A step often overlooked, wearing sunscreen can effectively delay signs of ageing. People with acne-prone skin are averse to the idea of using regular, greasy sunscreens for fear of clogged pores and oiliness. Acne-prone skin has specific needs, and if the formula is not right, sunscreen for face can trigger breakouts and irritation.</p>
               </div>
               <p class="f-regular">Here are some things you should keep in mind while buying the right sunblock for your acne-prone skin.</p> 
                  <ul data-aos="fade-up" data-aos-duration="1000" data-aos-delay="150">
                  <li class="f-semibold">1. Texture</li>
                  <p class="f-regular">Most sunscreens are not suitable for acne-prone skin as they tend to be too thick. Choose a sun cream for face that has a light, non-greasy formula. Also, oil-free formulas are great at keeping oiliness in check. Water-based formulas are most suitable for oily, acne-prone skin.</p>
                  <p class="f-regular">Also, sunscreens are available in various forms- creams, lotions, sprays, gels, sticks, etc. Usually, lotions, sprays and gels are more suitable for oily, acne-prone skin because of their light formulation and absorbability. These don’t generally leave a white cast and give skin a matte finish.</p>

                  <li class="f-semibold">2. Type</li>
                  <p class="f-regular">Sunscreens can be of two types depending on the way they provide protection- chemical and physical. Sunscreens with chemical protectants get absorbed into the skin and avoid sun damage from within. But this may irritate acne-prone skin. So, physical sunscreens are a better alternative for people with sensitive skin.</p>
                  <p class="f-regular">Physical sunscreens sit on the surface of the skin and create a physical barrier that deflects skin-damaging UV rays. A lot of people with acne-prone skin prefer using products with natural ingredients. You can try Bajaj Nomarks Ayurveda Antimarks Sunscreen, which is the best sunscreen for sensitive skin.</p>

                  <li class="f-semibold">3. Ingredients</li>
                  <strong>-What’s good for you?</strong>
                  <p class="f-regular">Look for ingredients like Wheat Germ Oil and Carrot Seed Oil that have natural sunscreen properties. Cucumber (Kheera) hydrates and soothes the skin and bring out the glow, and Mulethi helps reduce the appearance of spots. Such ingredients moisturize and help remove pimple marks.</p>
                  <p>Also, ingredients like zinc oxide and titanium dioxide provide physical barriers against the sun. Look for the term ‘non-comedogenic’ on the label. It means that the product doesn’t contain pore-clogging ingredients.</p>
                  <strong>-What’s bad for you?</strong>
                  <p>Stay away from ingredients like oxybenzone, avobenzone, octisalate, octocrylene, homosalate and octinoxate, present in most chemical sunscreens as these are harmful to the skin. These don’t just irritate acne-prone skin, but most of them disrupt hormonal balance. Even nanoparticles of zinc oxide and titanium dioxide are harmful, as it can enter your bloodstream through the pores. Choose a formula that is free of irritants like artificial fragrances, dyes, and parabens.</p>
                  <li class="f-semibold">4. SPF/Strength</li>
                  <p class="f-regular">The strength of a sunscreen against UVB rays is indicated by its Sun Protection Factor. Higher the number, stronger the protection. Similarly, protection against UVA rays is evaluated by the PA rating. More + signs mean stronger protection.</p>
                  <p class="f-regular">Ideally, a sunscreen of SPF 30 or above is enough for daily use. But if you are spending an extended period outdoors, go for higher SPF, that is water and sweat resistant too. Bajaj Nomarks Ayurveda Antimarks Sunscreen, also the best anti marks cream, is available in two variants- SPF 30 and SPF 50, with PA+++.</p>
                  <p class="f-regular">Stepping out without sunscreen is not an option. Some dermatologists even suggest using sunscreens at night. Finding the right sunscreen for you may take some trial and error. But once you’ve found one that suits your skin’s needs, it will be that much easier to deal with the acne. Don’t let it be a choice between acne and sun damage.</p>
